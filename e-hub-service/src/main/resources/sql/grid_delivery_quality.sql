  PRIMARY KEY (id),
  UNIQUE KEY uk_la_grid_market_status (aggregator_id, resource_type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='电网市场参与人工标记';
CREATE TABLE IF NOT EXISTS la_model_snapshot (
  id BIGINT NOT NULL AUTO_INCREMENT,
  aggregator_id VARCHAR(20) NOT NULL,
  snapshot_code VARCHAR(64) NOT NULL,
  snapshot_name VARCHAR(128) DEFAULT NULL,
  effective_start DATETIME NOT NULL,
  effective_end DATETIME DEFAULT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'EFFECTIVE',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_la_snapshot_code (aggregator_id, snapshot_code),
