CREATE TABLE IF NOT EXISTS la_grid_reconciliation (
  id BIGINT NOT NULL AUTO_INCREMENT,
  aggregator_id VARCHAR(20) NOT NULL,
  data_date DATE NOT NULL,
  resource_type_id VARCHAR(64) DEFAULT NULL COMMENT '能源类型ID',
  grid_channel_no VARCHAR(64) NOT NULL DEFAULT '',
  quarter_time DATETIME NOT NULL,
  snapshot_id BIGINT DEFAULT NULL,
  total_value DECIMAL(20,6) DEFAULT NULL,
  single_sum DECIMAL(20,6) DEFAULT NULL,
  difference DECIMAL(20,6) DEFAULT NULL,
  relative_difference DECIMAL(20,8) DEFAULT NULL,
  tolerance DECIMAL(20,6) DEFAULT NULL,
  reconciliation_status VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
  missing_single_count INT NOT NULL DEFAULT 0,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_la_grid_reconcile (aggregator_id, resource_type_id, grid_channel_no, quarter_time),
  KEY idx_la_grid_reconcile_date (aggregator_id, resource_type_id, data_date, reconciliation_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='总加单体对账结果';

CREATE TABLE IF NOT EXISTS la_grid_quality_issue (
  id BIGINT NOT NULL AUTO_INCREMENT,
  aggregator_id VARCHAR(20) NOT NULL,
  data_date DATE NOT NULL,
  period_id BIGINT DEFAULT NULL,
  resource_type_id VARCHAR(64) DEFAULT NULL COMMENT '能源类型ID',
  issue_key VARCHAR(255) NOT NULL COMMENT '同一问题的幂等业务键',
  issue_type VARCHAR(32) NOT NULL,
  issue_time DATETIME NOT NULL,
  grid_channel_no VARCHAR(64) DEFAULT NULL,
  single_code VARCHAR(128) DEFAULT NULL,
  device_id BIGINT DEFAULT NULL,
  reason VARCHAR(512) DEFAULT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
  remark VARCHAR(1024) DEFAULT NULL,
  handler_id VARCHAR(64) DEFAULT NULL,
  handler_name VARCHAR(128) DEFAULT NULL,
  first_detected_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_detected_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_time DATETIME DEFAULT NULL,
  current_detected TINYINT NOT NULL DEFAULT 1 COMMENT '本次自动核查是否仍存在',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_la_grid_issue_key (aggregator_id, issue_key),
  KEY idx_la_grid_issue_query (aggregator_id, data_date, issue_type, status),
  KEY idx_la_grid_issue_period (aggregator_id, period_id, data_date, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='电网上送质量问题';

