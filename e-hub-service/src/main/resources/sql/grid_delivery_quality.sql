CREATE TABLE IF NOT EXISTS la_grid_delivery_batch (
  id BIGINT NOT NULL AUTO_INCREMENT,
  aggregator_id VARCHAR(20) NOT NULL,
  data_date DATE NOT NULL,
  delivery_type VARCHAR(32) NOT NULL COMMENT 'TOTAL/SINGLE_MEAS',
  resource_type_id VARCHAR(64) DEFAULT NULL,
  grid_channel_no VARCHAR(64) NOT NULL DEFAULT '',
  snapshot_id BIGINT DEFAULT NULL,
  expected_count INT DEFAULT 0,
  prepared_count INT DEFAULT 0,
  sent_time DATETIME DEFAULT NULL,
  response_time DATETIME DEFAULT NULL,
  send_status VARCHAR(32) NOT NULL DEFAULT 'PREPARED',
  response_code VARCHAR(64) DEFAULT NULL,
  response_message VARCHAR(1024) DEFAULT NULL,
  request_payload LONGTEXT,
  response_payload LONGTEXT,
  attempt_no INT NOT NULL DEFAULT 1,
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_la_grid_batch_scope (aggregator_id, resource_type_id, data_date, delivery_type, grid_channel_no),
  KEY idx_la_grid_batch_status (send_status, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='电网上送审计批次';

CREATE TABLE IF NOT EXISTS la_grid_total_minute (
