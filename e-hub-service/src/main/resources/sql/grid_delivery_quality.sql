CREATE TABLE IF NOT EXISTS la_model_snapshot_device (
  id BIGINT NOT NULL AUTO_INCREMENT,
  snapshot_id BIGINT NOT NULL,
  aggregator_id VARCHAR(20) NOT NULL,
  ent_id VARCHAR(20) DEFAULT NULL,
  device_id BIGINT DEFAULT NULL,
  device_code VARCHAR(128) NOT NULL,
  point_code VARCHAR(64) NOT NULL DEFAULT 'P',
  single_code VARCHAR(128) DEFAULT NULL,
  single_name VARCHAR(128) DEFAULT NULL,
